const watchRegionNames = new Map<string, string>(WATCH_REGIONS.map((region) => [region.code, region.name]));

export const getBrowserWatchRegion = () => {
  const localeRegion = navigator.language.split('-')[1]?.toUpperCase();

  return localeRegion && watchRegionNames.has(localeRegion) ? localeRegion : DEFAULT_WATCH_REGION;
};

export const getWatchRegionName = (region: string) => watchRegionNames.get(region.toUpperCase()) ?? region;
